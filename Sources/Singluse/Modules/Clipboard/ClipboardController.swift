import AppKit
import Carbon.HIToolbox
import CryptoKit
import SingluseCore
import SwiftUI

@MainActor
final class ClipboardController: ObservableObject {
    @Published private(set) var history = ClipboardHistory()
    @Published var query = ""
    @Published var selectedIndex = 0
    @Published var isPanelVisible = false

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var isActive = false
    private var saveWork: DispatchWorkItem?
    private var panel: KeyablePanel?
    private var keyMonitor: Any?
    private var resignObserver: NSObjectProtocol?
    private var registeredHotkey: Int?

    /// Менеджеры паролей помечают такие данные этими типами. Их нельзя сохранять в историю.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    static let hotkeys: [(title: String, modifiers: UInt32)] = [
        ("⌥⌘V", UInt32(cmdKey | optionKey)),
        ("⇧⌘V", UInt32(cmdKey | shiftKey)),
        ("⌃⌘V", UInt32(cmdKey | controlKey)),
        ("⌃⌥V", UInt32(controlKey | optionKey)),
    ]

    static var hotkeyTitle: String { hotkeys[safe: AppSettings.shared.clipHotkey]?.title ?? "⌥⌘V" }

    private static let maxTextLength = 200_000
    private static let maxImageBytes = 20 * 1024 * 1024

    private static var directory: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("Singluse", isDirectory: true)
    }
    private static var imagesDirectory: URL { directory.appendingPathComponent("ClipImages", isDirectory: true) }
    private static var historyFile: URL { directory.appendingPathComponent("clipboard.json") }

    init() {
        lastChangeCount = pasteboard.changeCount
        load()
    }

    func update(active: Bool) {
        applyHistorySettings()
        if active, registeredHotkey != nil, registeredHotkey != AppSettings.shared.clipHotkey {
            unregisterHotKey()
            registerHotKey()
        }
        guard active != isActive else { return }
        isActive = active
        if active {
            lastChangeCount = pasteboard.changeCount
            timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
            timer?.tolerance = 0.1
            registerHotKey()
        } else {
            timer?.invalidate()
            timer = nil
            unregisterHotKey()
            closePanel()
        }
    }

    /// Лимит и срок хранения применяются сразу, а не при следующем копировании.
    private func applyHistorySettings() {
        let settings = AppSettings.shared
        var removed: [ClipItem] = []
        if history.limit != settings.clipLimit {
            removed += history.applyLimit(settings.clipLimit)
        }
        if settings.clipRetentionDays > 0 {
            removed += history.removeOlder(than: Date(timeIntervalSinceNow: -Double(settings.clipRetentionDays) * 86400))
        }
        guard !removed.isEmpty else { return }
        removed.forEach(deleteFiles(of:))
        scheduleSave()
    }

    /// Следующее изменение буфера сделали мы сами, его не надо записывать.
    func skipCurrentChange() {
        lastChangeCount = pasteboard.changeCount
    }

    // MARK: - Чтение буфера

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let frontmost = NSWorkspace.shared.frontmostApplication
        if let bundleID = frontmost?.bundleIdentifier, AppSettings.shared.clipExcludedApps.contains(bundleID) { return }
        guard let content = readContent() else { return }
        let item = ClipItem(content: content, sourceApp: frontmost?.localizedName)
        let evicted = history.add(item)
        evicted.forEach(deleteFiles(of:))
        scheduleSave()
    }

    private func readContent() -> ClipItem.Content? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL], !urls.isEmpty {
            return .files(urls.map(\.path))
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(String(text.prefix(Self.maxTextLength)))
        }
        if let image = NSImage(pasteboard: pasteboard), let png = pngData(from: image), png.count <= Self.maxImageBytes {
            let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            let name = hash.prefix(24) + ".png"
            do {
                try FileManager.default.createDirectory(at: Self.imagesDirectory, withIntermediateDirectories: true)
                try png.write(to: Self.imagesDirectory.appendingPathComponent(String(name)), options: .atomic)
            } catch {
                return nil
            }
            return .image(file: String(name), contentHash: hash)
        }
        return nil
    }

    private func pngData(from image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    func image(for item: ClipItem) -> NSImage? {
        guard case .image(let file, _) = item.content else { return nil }
        return NSImage(contentsOf: Self.imagesDirectory.appendingPathComponent(file))
    }

    // MARK: - Действия

    func copyToPasteboard(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        case .files(let paths):
            pasteboard.writeObjects(paths.map { URL(fileURLWithPath: $0) as NSURL })
        }
        skipCurrentChange()
        var moved = item
        moved.date = Date()
        history.add(moved)
        scheduleSave()
    }

    func paste(_ item: ClipItem) {
        copyToPasteboard(item)
        closePanel()
        guard AXIsProcessTrusted() else { return }
        // Даём панели закрыться, чтобы ⌘V ушло в приложение под ней.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) {
            Keystrokes.pasteCommand()
        }
    }

    func togglePin(_ item: ClipItem) {
        history.togglePin(id: item.id)
        scheduleSave()
    }

    func remove(_ item: ClipItem) {
        if let removed = history.remove(id: item.id) { deleteFiles(of: removed) }
        scheduleSave()
    }

    func clearUnpinned() {
        history.clearUnpinned().forEach(deleteFiles(of:))
        scheduleSave()
    }

    private func deleteFiles(of item: ClipItem) {
        guard case .image(let file, _) = item.content else { return }
        // Один файл может быть у новой записи с той же картинкой.
        let stillUsed = history.items.contains {
            if case .image(let other, _) = $0.content { return other == file }
            return false
        }
        if !stillUsed {
            try? FileManager.default.removeItem(at: Self.imagesDirectory.appendingPathComponent(file))
        }
    }

    // MARK: - Сохранение

    private func load() {
        guard let data = try? Data(contentsOf: Self.historyFile),
              let stored = try? JSONDecoder().decode(ClipboardHistory.self, from: data) else { return }
        history = stored
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated { self?.saveNow() }
        }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1, execute: work)
    }

    func saveNow() {
        saveWork?.cancel()
        guard let data = try? JSONEncoder().encode(history) else { return }
        let fileManager = FileManager.default
        try? fileManager.createDirectory(at: Self.directory, withIntermediateDirectories: true)
        // История может содержать личное, поэтому файл доступен только владельцу.
        try? data.write(to: Self.historyFile, options: [.atomic, .completeFileProtection])
        try? fileManager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: Self.historyFile.path)
    }

    // MARK: - Горячая клавиша ⌥⌘V (Carbon не требует никаких разрешений)

    private func registerHotKey() {
        let choice = AppSettings.shared.clipHotkey
        registeredHotkey = choice
        HotKeys.shared.register(
            id: 1,
            keyCode: kVK_ANSI_V,
            modifiers: Self.hotkeys[safe: choice]?.modifiers ?? UInt32(cmdKey | optionKey)
        ) { [weak self] in self?.togglePanel() }
    }

    private func unregisterHotKey() {
        HotKeys.shared.unregister(id: 1)
        registeredHotkey = nil
    }

    // MARK: - Всплывающая панель

    var results: [ClipItem] { history.visible(matching: query) }

    func togglePanel() {
        if panel?.isVisible == true { closePanel() } else { openPanel() }
    }

    private func openPanel() {
        query = ""
        selectedIndex = 0
        let size = NSSize(width: 560, height: 480)
        let screen = NSScreen.screens.first { $0.frame.contains(NSEvent.mouseLocation) } ?? NSScreen.main ?? NSScreen.screens[0]
        let origin = NSPoint(x: screen.visibleFrame.midX - size.width / 2, y: screen.visibleFrame.midY - size.height / 2 + 60)

        let panel: KeyablePanel
        if let existing = self.panel {
            panel = existing
        } else {
            panel = KeyablePanel(contentRect: NSRect(origin: origin, size: size), styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
            panel.level = .floating
            panel.isOpaque = false
            panel.backgroundColor = .clear
            panel.hasShadow = true
            panel.isReleasedWhenClosed = false
            panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
            let hosting = FirstMouseHostingView(rootView: ClipboardPanelView(controller: self))
            hosting.sizingOptions = []
            panel.contentView = hosting
            panel.hasShadow = true
            self.panel = panel
        }
        panel.setFrame(NSRect(origin: origin, size: size), display: true)
        panel.alphaValue = 0
        panel.makeKeyAndOrderFront(nil)
        withAnimation(Motion.panel) { isPanelVisible = true }
        NSAnimationContext.runAnimationGroup { context in
            context.duration = 0.16
            panel.animator().alphaValue = 1
        }

        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            nonisolated(unsafe) let event = event
            let handled = MainActor.assumeIsolated { self?.handleKey(event) == true }
            return handled ? nil : event
        }
        resignObserver = NotificationCenter.default.addObserver(forName: NSWindow.didResignKeyNotification, object: panel, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.closePanel() }
        }
    }

    func closePanel() {
        if let panel, panel.isVisible {
            withAnimation(Motion.panel) { isPanelVisible = false }
            NSAnimationContext.runAnimationGroup({ context in
                context.duration = 0.16
                panel.animator().alphaValue = 0
            }, completionHandler: {
                if panel.alphaValue == 0 { panel.orderOut(nil) }
            })
        }
        if let keyMonitor { NSEvent.removeMonitor(keyMonitor) }
        keyMonitor = nil
        if let resignObserver { NotificationCenter.default.removeObserver(resignObserver) }
        resignObserver = nil
    }

    private func handleKey(_ event: NSEvent) -> Bool {
        let items = results
        switch Int(event.keyCode) {
        case kVK_Escape:
            closePanel()
            return true
        case kVK_DownArrow:
            selectedIndex = min(selectedIndex + 1, max(items.count - 1, 0))
            return true
        case kVK_UpArrow:
            selectedIndex = max(selectedIndex - 1, 0)
            return true
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if items.indices.contains(selectedIndex) { paste(items[selectedIndex]) }
            return true
        default:
            // ⌘1…⌘9 — мгновенная вставка записи по номеру.
            if event.modifierFlags.contains(.command), let digit = event.charactersIgnoringModifiers.flatMap(Int.init), digit >= 1, digit <= 9 {
                if items.indices.contains(digit - 1) { paste(items[digit - 1]) }
                return true
            }
            return false
        }
    }
}

// MARK: - Интерфейс панели

struct ClipboardPanelView: View {
    @ObservedObject var controller: ClipboardController
    @FocusState private var searchFocused: Bool

    var body: some View {
        let items = controller.results
        VStack(spacing: 0) {
            HStack(spacing: 10) {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("Поиск по истории", text: $controller.query)
                    .textFieldStyle(.plain)
                    .font(.system(size: 17))
                    .focused($searchFocused)
                    .onChange(of: controller.query) { _, _ in controller.selectedIndex = 0 }
                Text(ClipboardController.hotkeyTitle).font(.caption.monospaced()).foregroundStyle(.tertiary)
            }
            .padding(16)
            Divider().opacity(0.5)

            if items.isEmpty {
                VStack(spacing: 8) {
                    Image(systemName: "doc.on.clipboard").font(.system(size: 30)).foregroundStyle(.tertiary)
                    Text(controller.query.isEmpty ? "Пока ничего не скопировано" : "Ничего не найдено")
                        .foregroundStyle(.secondary)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            ForEach(Array(items.enumerated()), id: \.element.id) { index, item in
                                ClipRow(item: item, index: index, isSelected: index == controller.selectedIndex, controller: controller)
                                    .id(item.id)
                                    .onTapGesture { controller.paste(item) }
                            }
                        }
                        .padding(8)
                    }
                    .onChange(of: controller.selectedIndex) { _, index in
                        if items.indices.contains(index) { proxy.scrollTo(items[index].id) }
                    }
                }
            }

            Divider().opacity(0.5)
            HStack(spacing: 14) {
                hint("↩", L("вставить"))
                hint("↑↓", L("выбрать"))
                hint("⌘1–9", L("быстро"))
                Spacer()
                hint("esc", L("закрыть"))
            }
            .padding(.horizontal, 16)
            .padding(.vertical, 10)
        }
        .glassEffect(.regular, in: .rect(cornerRadius: 24))
        .scaleEffect(controller.isPanelVisible ? 1 : 0.96)
        .onAppear { searchFocused = true }
        .onChange(of: controller.isPanelVisible) { _, visible in
            if visible { searchFocused = true }
        }
    }

    private func hint(_ key: String, _ text: String) -> some View {
        HStack(spacing: 4) {
            Text(key).font(.caption.weight(.semibold)).foregroundStyle(.secondary)
            Text(text).font(.caption).foregroundStyle(.tertiary)
        }
    }
}

struct ClipRow: View {
    let item: ClipItem
    let index: Int
    let isSelected: Bool
    @ObservedObject var controller: ClipboardController
    @State private var hovering = false

    var body: some View {
        HStack(spacing: 12) {
            ClipThumbnail(item: item, controller: controller)
            VStack(alignment: .leading, spacing: 3) {
                Text(ClipFormat.title(item)).lineLimit(2).font(.system(size: 13))
                Text(ClipFormat.caption(item)).font(.caption).foregroundStyle(.secondary).lineLimit(1)
            }
            Spacer(minLength: 8)
            if hovering || item.pinned {
                Button { controller.togglePin(item) } label: {
                    Image(systemName: item.pinned ? "pin.fill" : "pin")
                }
                .buttonStyle(.plain)
                .foregroundStyle(item.pinned ? Color.orange : .secondary)
                .help(item.pinned ? "Открепить" : "Закрепить")
            }
            if hovering {
                Button { controller.remove(item) } label: { Image(systemName: "trash") }
                    .buttonStyle(.plain)
                    .foregroundStyle(.secondary)
                    .help("Удалить")
            } else if index < 9 {
                Text("⌘\(index + 1)").font(.caption.monospaced()).foregroundStyle(.tertiary)
            }
        }
        .padding(.horizontal, 10)
        .padding(.vertical, 8)
        .background(
            RoundedRectangle(cornerRadius: 10, style: .continuous)
                .fill(isSelected ? Color.accentColor.opacity(0.28) : hovering ? Color.primary.opacity(0.07) : .clear)
        )
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
        .animation(Motion.hover, value: hovering)
        .animation(Motion.hover, value: isSelected)
    }
}

struct ClipThumbnail: View {
    let item: ClipItem
    @ObservedObject var controller: ClipboardController

    var body: some View {
        Group {
            switch item.content {
            case .image:
                if let image = controller.image(for: item) {
                    Image(nsImage: image).resizable().scaledToFill()
                } else {
                    Image(systemName: "photo").foregroundStyle(.secondary)
                }
            case .files(let paths):
                Image(nsImage: NSWorkspace.shared.icon(forFile: paths.first ?? "/")).resizable().scaledToFit().padding(3)
            case .text:
                Image(systemName: "text.alignleft").foregroundStyle(.secondary)
            }
        }
        .frame(width: 34, height: 34)
        .background(Color.primary.opacity(0.07))
        .clipShape(RoundedRectangle(cornerRadius: 8, style: .continuous))
    }
}

extension Array {
    subscript(safe index: Int) -> Element? { indices.contains(index) ? self[index] : nil }
}

enum ClipFormat {
    private static let relative: RelativeDateTimeFormatter = {
        let formatter = RelativeDateTimeFormatter()
        formatter.locale = .current
        formatter.unitsStyle = .short
        return formatter
    }()

    static func title(_ item: ClipItem) -> String {
        switch item.content {
        case .text(let text):
            return text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ")
        case .image:
            return L("Картинка")
        case .files(let paths):
            let name = URL(fileURLWithPath: paths.first ?? "").lastPathComponent
            return paths.count > 1 ? "\(name) +\(paths.count - 1)" : name
        }
    }

    static func caption(_ item: ClipItem) -> String {
        let time = relative.localizedString(for: item.date, relativeTo: Date())
        if let source = item.sourceApp { return "\(source) · \(time)" }
        return time
    }
}
